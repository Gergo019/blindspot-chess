-- #36: a drill accepts every good-enough move, and every legal move of its position has a
-- stored verdict from the analysis service's POST /judge (#78, ADR 0008). Answers are checked
-- by looking the move up; a move without a verdict is not a legal move in the position.

-- Nothing created drills before #36 (no service, job or API used the table), so there are no
-- rows to migrate. Should a hand-made row exist anyway, stop with a clear message instead of
-- inventing verdicts for it.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM drills) THEN
        RAISE EXCEPTION 'V5: drills exist without move verdicts; delete them first (nothing created drills before #36)';
    END IF;
END $$;

-- The task of an own-game drill (ADR 0008): find a safe move in the position before the
-- mistake, or see the opponent's winning capture after it. One drill per finding and task.
ALTER TABLE drills
    ADD COLUMN task VARCHAR(20) NOT NULL DEFAULT 'FIND_SAFE_MOVE'
        CHECK (task IN ('FIND_SAFE_MOVE', 'SEE_THE_CAPTURE')),
    DROP CONSTRAINT drills_user_finding_uq,
    ADD CONSTRAINT drills_user_finding_task_uq UNIQUE (user_id, finding_id, task);

-- How the verdicts were produced (product rule 4), and the threshold they were judged against.
ALTER TABLE drills
    ADD COLUMN verdict_engine_version VARCHAR(30)  NOT NULL,
    ADD COLUMN verdict_engine_depth   INTEGER      NOT NULL CHECK (verdict_engine_depth > 0),
    ADD COLUMN verdict_engine_threads INTEGER      NOT NULL CHECK (verdict_engine_threads > 0),
    ADD COLUMN verdict_engine_hash_mb INTEGER      NOT NULL CHECK (verdict_engine_hash_mb > 0),
    ADD COLUMN accept_below           NUMERIC(5, 4) NOT NULL CHECK (accept_below > 0);

COMMENT ON COLUMN drills.solution_uci IS 'The engine''s first choice (the best verdict), for display; answers are checked against drill_move_verdicts';

-- One row per legal move of the drill's position. The score is the value after the move
-- (White's point of view); chances_drop is the loss in the mover's winning chances against the
-- best move (the service's "drop"; DROP is a reserved word); the refutation is the engine's line
-- after the move, the evidence for a wrong answer.
CREATE TABLE drill_move_verdicts (
    drill_id        BIGINT        NOT NULL REFERENCES drills (id) ON DELETE CASCADE,
    move_uci        VARCHAR(5)    NOT NULL,
    move_san        VARCHAR(10)   NOT NULL,
    score_cp        INTEGER,
    score_mate      INTEGER,
    chances_drop    NUMERIC(5, 4) NOT NULL CHECK (chances_drop >= 0),
    accepted        BOOLEAN       NOT NULL,
    refutation_uci  TEXT          NOT NULL DEFAULT '',
    PRIMARY KEY (drill_id, move_uci),
    CONSTRAINT drill_move_verdicts_one_score CHECK ((score_cp IS NULL) <> (score_mate IS NULL))
);

-- Findings whose drill could not be prepared yet, or never can be. A finding with no row here
-- and no drill is simply waiting for the job. PENDING: retried at next_attempt_at (the time
-- budget was exceeded, the call timed out, or the response could not be stored). SKIPPED: never
-- retried (the position cannot be judged, or the verdicts accept the game's mistake).
CREATE TABLE drill_preparations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id       BIGINT       NOT NULL REFERENCES mistake_findings (id) ON DELETE CASCADE,
    task             VARCHAR(20)  NOT NULL CHECK (task IN ('FIND_SAFE_MOVE', 'SEE_THE_CAPTURE')),
    status           VARCHAR(10)  NOT NULL CHECK (status IN ('PENDING', 'SKIPPED')),
    attempts         INTEGER      NOT NULL CHECK (attempts >= 1),
    next_attempt_at  TIMESTAMPTZ,
    last_error       TEXT         NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT drill_preparations_finding_task_uq UNIQUE (finding_id, task),
    CONSTRAINT drill_preparations_pending_has_time CHECK ((status = 'PENDING') = (next_attempt_at IS NOT NULL))
);

CREATE INDEX drill_preparations_due_idx ON drill_preparations (next_attempt_at) WHERE status = 'PENDING';
