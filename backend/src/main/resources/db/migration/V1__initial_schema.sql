-- BlindSpot initial schema.
-- Bounded contexts: account (who), game (imported games), analysis (engine
-- evaluations and AI explanations), training (spaced-repetition drills).
-- Never edit a migration after it has been merged to main; add V<n>__*.sql instead.

-- ===========================================================================
-- Account
-- ===========================================================================
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL UNIQUE,
    email       VARCHAR(255) UNIQUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- A user's account on a chess platform, used to import their games.
CREATE TABLE chess_accounts (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    platform           VARCHAR(20)  NOT NULL CHECK (platform IN ('LICHESS', 'CHESS_COM')),
    platform_username  VARCHAR(100) NOT NULL,
    last_synced_at     TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chess_accounts_platform_username_uq UNIQUE (platform, platform_username)
);

CREATE INDEX chess_accounts_user_id_idx ON chess_accounts (user_id);

-- ===========================================================================
-- Game
-- ===========================================================================
CREATE TABLE games (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id         BIGINT       NOT NULL REFERENCES chess_accounts (id) ON DELETE CASCADE,
    external_id        VARCHAR(100) NOT NULL,       -- the platform's game id
    played_at          TIMESTAMPTZ  NOT NULL,
    speed              VARCHAR(20)  NOT NULL
                       CHECK (speed IN ('BULLET', 'BLITZ', 'RAPID', 'CLASSICAL', 'CORRESPONDENCE')),
    time_control       VARCHAR(20),                 -- e.g. "300+3"
    rated              BOOLEAN      NOT NULL,
    user_color         VARCHAR(5)   NOT NULL CHECK (user_color IN ('WHITE', 'BLACK')),
    result             VARCHAR(5)   NOT NULL CHECK (result IN ('WIN', 'LOSS', 'DRAW')),
    user_rating        INTEGER,
    opponent_name      VARCHAR(100),
    opponent_rating    INTEGER,
    opening_eco        VARCHAR(3),                  -- e.g. "B90"
    opening_name       VARCHAR(255),
    pgn                TEXT         NOT NULL,
    analysis_status    VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                       CHECK (analysis_status IN ('PENDING', 'RUNNING', 'DONE', 'FAILED')),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT games_account_external_id_uq UNIQUE (account_id, external_id)
);

CREATE INDEX games_account_played_at_idx ON games (account_id, played_at DESC);
CREATE INDEX games_analysis_status_idx  ON games (analysis_status) WHERE analysis_status <> 'DONE';

-- ===========================================================================
-- Analysis
-- ===========================================================================
-- Engine evaluation of every half-move (ply) of a game. Scores are from
-- White's point of view; exactly one of *_cp / mate_* is set per position.
-- engine_version + engine_depth make every result reproducible.
CREATE TABLE move_evaluations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id             BIGINT       NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    ply                 INTEGER      NOT NULL CHECK (ply >= 1),
    by_user             BOOLEAN      NOT NULL,      -- played by the user, not the opponent
    fen_before          VARCHAR(100) NOT NULL,
    move_uci            VARCHAR(5)   NOT NULL,      -- e.g. "e2e4", "e7e8q"
    move_san            VARCHAR(10)  NOT NULL,      -- e.g. "Nxf7+"
    best_move_uci       VARCHAR(5)   NOT NULL,
    eval_before_cp      INTEGER,
    mate_before         INTEGER,
    eval_after_cp       INTEGER,
    mate_after          INTEGER,
    engine_version      VARCHAR(30)  NOT NULL,      -- e.g. "Stockfish 17.1"
    engine_depth        INTEGER      NOT NULL CHECK (engine_depth > 0),
    classification      VARCHAR(20)  NOT NULL
                        CHECK (classification IN ('BEST', 'GOOD', 'INACCURACY', 'MISTAKE', 'BLUNDER')),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT move_evaluations_game_ply_uq UNIQUE (game_id, ply),
    CONSTRAINT move_evaluations_before_one_score CHECK ((eval_before_cp IS NULL) <> (mate_before IS NULL)),
    CONSTRAINT move_evaluations_after_one_score  CHECK ((eval_after_cp  IS NULL) <> (mate_after  IS NULL))
);

CREATE INDEX move_evaluations_mistakes_idx ON move_evaluations (game_id)
    WHERE by_user AND classification IN ('MISTAKE', 'BLUNDER');

-- A detected motif behind one of the user's mistakes, with the line that
-- proves it. Product rule: every claim shown to a player has board evidence.
CREATE TABLE mistake_findings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    move_evaluation_id  BIGINT      NOT NULL REFERENCES move_evaluations (id) ON DELETE CASCADE,
    motif               VARCHAR(30) NOT NULL CHECK (motif IN ('ALLOWED_KNIGHT_FORK', 'HANGING_PIECE')),
    evidence_line_uci   TEXT        NOT NULL,       -- space-separated moves that demonstrate the motif
    detector_version    VARCHAR(20) NOT NULL,       -- re-run detection when the detector changes
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT mistake_findings_move_motif_uq UNIQUE (move_evaluation_id, motif)
);

CREATE INDEX mistake_findings_motif_idx ON mistake_findings (motif);

-- An explanation of a finding. Code extracts structured facts first; the text
-- is either a template filled from those facts or an LLM explanation of them.
-- Only PASSED explanations are ever shown; the modes are compared in evaluation.
CREATE TABLE explanations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id           BIGINT       NOT NULL REFERENCES mistake_findings (id) ON DELETE CASCADE,
    mode                 VARCHAR(20)  NOT NULL CHECK (mode IN ('TEMPLATE', 'LLM_FREE', 'LLM_FACTS')),
    model                VARCHAR(100),               -- NULL for templates
    prompt_version       VARCHAR(20),                -- NULL for templates
    facts                JSONB        NOT NULL,      -- the checked facts the text may use
    content              TEXT         NOT NULL,
    verification_status  VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
                         CHECK (verification_status IN ('PENDING', 'PASSED', 'FAILED')),
    unsupported_claims   INTEGER      CHECK (unsupported_claims >= 0),
    verification_notes   TEXT,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT explanations_llm_has_model CHECK (mode = 'TEMPLATE' OR (model IS NOT NULL AND prompt_version IS NOT NULL))
);

CREATE INDEX explanations_finding_id_idx ON explanations (finding_id);

-- ===========================================================================
-- Training
-- ===========================================================================
-- OWN_GAME drill: a position from the user's game, find the move they missed.
-- TRANSFER drill: an unseen Lichess puzzle with the same motif, which tests
-- whether the lesson carries over rather than whether the move was memorised.
-- Transfer is measured over several puzzles of comparable rating, not one.
-- Scheduling follows a simplified SM-2 spaced repetition.
CREATE TABLE drills (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind                VARCHAR(20)   NOT NULL CHECK (kind IN ('OWN_GAME', 'TRANSFER')),
    motif               VARCHAR(30)   NOT NULL CHECK (motif IN ('ALLOWED_KNIGHT_FORK', 'HANGING_PIECE')),
    finding_id          BIGINT        REFERENCES mistake_findings (id) ON DELETE CASCADE,
    puzzle_id           VARCHAR(10),                -- Lichess puzzle id
    puzzle_rating       INTEGER       CHECK (puzzle_rating > 0),
    fen                 VARCHAR(100)  NOT NULL,
    solution_uci        VARCHAR(5)    NOT NULL,
    repetitions         INTEGER       NOT NULL DEFAULT 0 CHECK (repetitions >= 0),
    interval_days       INTEGER       NOT NULL DEFAULT 0 CHECK (interval_days >= 0),
    ease_factor         NUMERIC(4, 2) NOT NULL DEFAULT 2.50 CHECK (ease_factor >= 1.30),
    next_review_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT drills_source_matches_kind CHECK (
        (kind = 'OWN_GAME' AND finding_id IS NOT NULL AND puzzle_id IS NULL AND puzzle_rating IS NULL) OR
        (kind = 'TRANSFER' AND puzzle_id IS NOT NULL AND puzzle_rating IS NOT NULL AND finding_id IS NULL)),
    CONSTRAINT drills_user_finding_uq UNIQUE (user_id, finding_id),
    CONSTRAINT drills_user_puzzle_uq  UNIQUE (user_id, puzzle_id)
);

CREATE INDEX drills_due_idx ON drills (user_id, next_review_at);

CREATE TABLE drill_attempts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drill_id      BIGINT      NOT NULL REFERENCES drills (id) ON DELETE CASCADE,
    move_uci      VARCHAR(5)  NOT NULL,
    correct       BOOLEAN     NOT NULL,
    attempted_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX drill_attempts_drill_id_idx ON drill_attempts (drill_id);
