-- #88: the lesson model of the learning journey (ADR 0008, "Curriculum, progress and what is stored").
-- The curriculum itself (units, lessons, sizes, the mastery rule) is code; the database stores only
-- which drills belong to which lesson for a user, and when the user passed the lesson's mastery
-- check. Progress ("3 of 5 solved first try") is derived from drill_attempts, never counted here.

-- One lesson of the curriculum, assigned to one user. It does not change when new games are
-- analysed. mastered_at is set only by passing the mastery check and is never cleared: it records
-- what happened, so it stays even when a re-analysis deletes the lesson's drills.
CREATE TABLE lesson_assignments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    lesson_key          VARCHAR(40)  NOT NULL,
    curriculum_version  VARCHAR(20)  NOT NULL,
    mastered_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT lesson_assignments_user_lesson_uq UNIQUE (user_id, lesson_key)
);

-- The drills of one assigned lesson, in order. PRACTICE items can be answered again; CHECK items
-- form the mastery check and are answered once. A retry of the check adds a new pair of CHECK items
-- on unused positions (amendment of 2026-11-27), so a drill appears at most once per lesson.
-- Items go with their drill (a re-analysis deletes findings, their drills and so these items).
CREATE TABLE lesson_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id  BIGINT       NOT NULL REFERENCES lesson_assignments (id) ON DELETE CASCADE,
    drill_id       BIGINT       NOT NULL REFERENCES drills (id) ON DELETE CASCADE,
    position       INTEGER      NOT NULL CHECK (position >= 1),
    role           VARCHAR(10)  NOT NULL CHECK (role IN ('PRACTICE', 'CHECK')),
    -- Derived from role, only so that drill_attempts can reference it (below).
    is_check       BOOLEAN      GENERATED ALWAYS AS (role = 'CHECK') STORED,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT lesson_items_assignment_position_uq UNIQUE (assignment_id, position),
    CONSTRAINT lesson_items_assignment_drill_uq UNIQUE (assignment_id, drill_id),
    CONSTRAINT lesson_items_attempt_ref_uq UNIQUE (id, drill_id, is_check)
);

CREATE INDEX lesson_items_drill_id_idx ON lesson_items (drill_id);

-- An attempt made inside a lesson names its item; a review from the SM-2 queue has none.
-- is_check is copied from the item's role because a partial index cannot look at another table:
-- the index below allows one attempt per check item. The composite foreign key makes the copy
-- (and the drill) agree with the item, so the copy cannot drift.
ALTER TABLE drill_attempts
    ADD COLUMN lesson_item_id BIGINT,
    ADD COLUMN is_check BOOLEAN NOT NULL DEFAULT false,
    ADD CONSTRAINT drill_attempts_lesson_item_fk FOREIGN KEY (lesson_item_id, drill_id, is_check)
        REFERENCES lesson_items (id, drill_id, is_check) ON DELETE CASCADE,
    ADD CONSTRAINT drill_attempts_check_has_item CHECK (NOT is_check OR lesson_item_id IS NOT NULL);

CREATE UNIQUE INDEX drill_attempts_one_per_check_item_uq ON drill_attempts (lesson_item_id) WHERE is_check;
CREATE INDEX drill_attempts_lesson_item_id_idx ON drill_attempts (lesson_item_id);
